#!/usr/bin/env python3
"""Generate the v2-only gate table: (v2 contract) - (v1 contract).

`OCSERVE_V2` is documented as "the whole v2 runtime stays dark until
acceptance", but only 67 of 179 v2 handlers honoured it (2026-10-20 audit).
The remaining surface leaked: `GET /api/config`, `/api/config/shell`,
`/api/debug/location`, `/api/experimental/migration/v1` all answered 200 with
the flag unset on a live server.

The fix must not gate `/api/*` wholesale: the frozen 1.18.31 contract already
contains 58 `/api/*` operations, and the 1.18.31 TUI calls `client.v2.*` for 18
methods on every mount. Gating those would break the clients ocserve exists to
serve. The gate surface is therefore mechanical and spec-derived:

    v2-only = (operations in 2.0.28) - (operations in 1.18.31)

That definition has no hand list and no judgement, and it re-derives itself on
every upstream bump (`scripts/extract-spec.sh` calls this script).

Output is a TSV of `METHOD<TAB>router_path`, using the ROUTER spelling of
wildcards (`/api/fs/read/*` -> `/api/fs/read/{*path}`) because the gate matches
on `MatchedPath`. It lives inside `crates/ocserve-http/assets/` so it is
packaged with the crate (guard rule 30: assets outside a crate root do not
reach `cargo install`).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECS = ROOT / "crates/ocserve-core/assets/openapi"
OUT = ROOT / "crates/ocserve-http/assets/openapi/v2-only.tsv"
METHODS = ("get", "post", "put", "patch", "delete")


def ops(spec: dict) -> set[tuple[str, str]]:
    out = set()
    for path, item in spec.get("paths", {}).items():
        for method in item:
            if method in METHODS:
                out.add((method.upper(), path))
    return out


def router_path(spec_path: str) -> str:
    # axum spells a trailing wildcard `{*name}`; the contract spells it `*`.
    if spec_path.endswith("/*"):
        return spec_path[:-2] + "/{*path}"
    return spec_path


def render(v1: dict, v2: dict) -> str:
    only = sorted(ops(v2) - ops(v1), key=lambda x: (x[1], x[0]))
    rows = [f"{method}\t{router_path(path)}" for method, path in only]
    return (
        "# generated by scripts/gen-v2-gate.py — do not hand-edit\n"
        "# (2.0.28 operations) - (1.18.31 operations), router path spelling\n"
        + "\n".join(rows)
        + "\n"
    )


def main() -> int:
    check = "--check" in sys.argv
    v1 = json.load(open(SPECS / "1.18.31.json"))
    v2 = json.load(open(SPECS / "2.0.28.json"))
    body = render(v1, v2)
    if check:
        # Guard mode: the committed table must equal what the specs imply.
        # A regenerated contract without a regenerated table reopens the
        # leak this gate exists to close.
        current = OUT.read_text() if OUT.exists() else ""
        if current != body:
            print(
                f"FAIL: {OUT.relative_to(ROOT)} is stale — run scripts/gen-v2-gate.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok (v2-only gate table current: {len(body.strip().splitlines()) - 2} operations)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body)
    print(f"  v2-only gate: {len(body.strip().splitlines()) - 2} operations -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
